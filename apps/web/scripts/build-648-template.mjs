/**
 * Regenerates lib/form-648-template.ts from HMRC's official 64-8 PDF.
 *
 * The source we were given is the GNS Associates Limited copy, which is the
 * genuine HMRC form with a live AcroForm and OUR agent details already filled
 * in. Every one of those values is cleared here so the shipped template is
 * firm-neutral: agent details are written at render time from lib/firms.ts.
 * If GNS's codes were left baked in they would appear on an LLP or Galaxy
 * form whenever that firm's own codes were missing — silently wrong, and on
 * a document that authorises HMRC access.
 *
 * Usage: node scripts/build-648-template.mjs <path-to-source.pdf>
 */
import { PDFDocument, PDFName } from "pdf-lib";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-648-template.mjs <source.pdf>");
  process.exit(1);
}

const doc = await PDFDocument.load(fs.readFileSync(src), { ignoreEncryption: true });
const form = doc.getForm();

let cleared = 0;
let unticked = 0;
for (const field of form.getFields()) {
  const kind = field.constructor.name;
  if (kind === "PDFTextField") {
    if (field.getText()) cleared++;
    field.setText("");
  } else if (kind === "PDFCheckBox") {
    if (field.isChecked()) unticked++;
    field.uncheck();
  }
}

// A "Clear form" push-button sits on page 1. Left in place it would let anyone
// wipe a completed — possibly signed — authorisation with one click.
let removedButton = false;
const acro = doc.catalog.lookup(PDFName.of("AcroForm"));
const fields = acro?.lookup(PDFName.of("Fields"));
if (fields?.asArray) {
  const keep = fields.asArray().filter((ref) => {
    const f = doc.context.lookup(ref);
    const t = f?.get?.(PDFName.of("T"));
    const name = t?.asString ? t.asString() : "";
    if (name === "Clear form") {
      removedButton = true;
      return false;
    }
    return true;
  });
  while (fields.size() > 0) fields.remove(0);
  keep.forEach((ref) => fields.push(ref));
}

/**
 * Reattach every widget to its page.
 *
 * The source file lists no annotations on any page — the fields exist only in
 * the AcroForm tree, each widget pointing at its page via /P but no page
 * pointing back. Acrobat tolerates that; nothing else does. Left as-is the
 * fields cannot be rendered or flattened, and the form comes out BLANK while
 * still reporting the right page count, which is exactly the kind of silent
 * failure that would put an empty authorisation in front of a client.
 */
let reattached = 0;
const pageRefs = doc.getPages().map((p) => p.ref);
for (const field of form.getFields()) {
  for (const widget of field.acroField.getWidgets()) {
    const widgetRef = doc.context.getObjectRef(widget.dict);
    const pRef = widget.P();
    const pageIdx = pageRefs.findIndex((r) => pRef && r.tag === pRef.tag);
    if (!widgetRef || pageIdx < 0) continue;
    const page = doc.getPages()[pageIdx];
    let annots = page.node.get(PDFName.of("Annots"));
    if (!annots?.asArray) {
      page.node.set(PDFName.of("Annots"), doc.context.obj([]));
      annots = page.node.get(PDFName.of("Annots"));
    }
    const already = annots.asArray().some((r) => r.tag === widgetRef.tag);
    if (!already) {
      annots.push(widgetRef);
      reattached++;
    }
  }
}

// Appearances are generated at fill time from a known font, so the viewer must
// not be asked to invent its own.
const acroDict = doc.catalog.lookup(PDFName.of("AcroForm"));
acroDict?.set?.(PDFName.of("NeedAppearances"), doc.context.obj(false));

const bytes = await doc.save({ useObjectStreams: true });
const srcSize = fs.statSync(src).size;

const out = path.join(__dirname, "..", "lib", "form-648-template.ts");
fs.writeFileSync(
  out,
  `/**\n` +
    ` * HMRC form 64-8 (Authorising your agent), blank.\n` +
    ` *\n` +
    ` * Generated by scripts/build-648-template.mjs — do not hand-edit.\n` +
    ` * Every field is empty and every box unticked; agent details and the tick\n` +
    ` * set are written per firm at render time. Base64 rather than a file on\n` +
    ` * disk because that is how this app ships binaries to the cPanel host.\n` +
    ` */\n\n` +
    `export const FORM_648_TEMPLATE_BASE64 =\n  "${Buffer.from(bytes).toString("base64")}";\n`,
  "utf8",
);

console.log(`source        ${src}`);
console.log(`cleared       ${cleared} text fields, ${unticked} ticked boxes`);
console.log(`Clear form    ${removedButton ? "removed" : "NOT FOUND"}`);
console.log(`reattached    ${reattached} widgets to pages`);
console.log(`pdf bytes     ${srcSize} -> ${bytes.length}`);
console.log(`wrote         ${out} (${fs.statSync(out).size} bytes)`);
